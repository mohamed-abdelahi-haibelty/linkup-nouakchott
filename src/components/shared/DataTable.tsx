"use client";

import {
  ColumnDef,
  flexRender,
  getCoreRowModel,
  getFacetedRowModel,
  getFacetedUniqueValues,
  getFilteredRowModel,
  getPaginationRowModel,
  useReactTable,
} from "@tanstack/react-table";

import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { DataTablePagination } from "./DataTablePagination";
import { DataTableToolbar } from "./DataTableToolbar";

interface DataTableProps<TData, TValue> {
  columns: ColumnDef<TData, TValue>[];
  data: TData[];
  filters?: {
    columnId: string;
    title: string;
    options: {
      label: string;
      value: string;
      icon?: React.ComponentType<{ className?: string }>;
    }[];
  }[];
  /** which columns should receive the search string (e.g. ["name","email","phone"]) */
  searchColumns?: string[];
  /** Placeholder for the search input */
  searchPlaceholder?: string;
  deleteAction?: (ids: string[]) => Promise<{ message: string }>;
  /** Optional labels for the confirmation dialog */
  deleteConfirmTitle?: string;
  deleteConfirmDescription?: string;
  deleteConfirmLabel?: string;
  deleteCancelLabel?: string;
}

export function DataTable<TData, TValue>({
  columns,
  data,
  filters,
  searchColumns = ["title"],
  searchPlaceholder = "Search...",
  deleteAction,
  deleteConfirmTitle = "Delete Selected Items",
  deleteConfirmDescription,
  deleteConfirmLabel = "Delete",
  deleteCancelLabel = "Cancel",
}: DataTableProps<TData, TValue>) {
  const table = useReactTable({
    data,
    columns,
    getCoreRowModel: getCoreRowModel(),
    getPaginationRowModel: getPaginationRowModel(),
    getFilteredRowModel: getFilteredRowModel(),
    getFacetedRowModel: getFacetedRowModel(),
    getFacetedUniqueValues: getFacetedUniqueValues(),
  });

  return (
    <div className="flex flex-col gap-4">
      <DataTableToolbar
        table={table}
        filters={filters}
        searchColumns={searchColumns}
        searchPlaceholder={searchPlaceholder}
        deleteAction={deleteAction}
        deleteConfirmDescription={deleteConfirmDescription}
        deleteConfirmTitle={deleteConfirmTitle}
        deleteConfirmLabel={deleteConfirmLabel}
        deleteCancelLabel={deleteCancelLabel}
      />
      <div className="overflow-hidden rounded-md border">
        <Table className="bg-card">
          <TableHeader>
            {table.getHeaderGroups().map((headerGroup) => (
              <TableRow key={headerGroup.id}>
                {headerGroup.headers.map((header) => {
                  return (
                    <TableHead key={header.id}>
                      {header.isPlaceholder
                        ? null
                        : flexRender(
                            header.column.columnDef.header,
                            header.getContext()
                          )}
                    </TableHead>
                  );
                })}
              </TableRow>
            ))}
          </TableHeader>
          <TableBody>
            {table.getRowModel().rows?.length ? (
              table.getRowModel().rows.map((row) => (
                <TableRow
                  key={row.id}
                  data-state={row.getIsSelected() && "selected"}
                >
                  {row.getVisibleCells().map((cell) => (
                    <TableCell key={cell.id}>
                      {flexRender(
                        cell.column.columnDef.cell,
                        cell.getContext()
                      )}
                    </TableCell>
                  ))}
                </TableRow>
              ))
            ) : (
              <TableRow>
                <TableCell
                  colSpan={columns.length}
                  className="h-24 text-center"
                >
                  No results.
                </TableCell>
              </TableRow>
            )}
          </TableBody>
        </Table>
      </div>
      <DataTablePagination table={table} />
    </div>
  );
}
